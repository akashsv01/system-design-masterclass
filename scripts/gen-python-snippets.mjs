// Generates src/content/python.generated.ts: the exact text of every learner-facing Python file,
// so lessons show code that pytest has verified. Runs before dev, build and test.
import { readdirSync, readFileSync, writeFileSync, statSync } from 'node:fs';
import { join } from 'node:path';
const root = 'python';
const out = {};
for (const dir of ['sdm', 'blanks']) {
  for (const f of readdirSync(join(root, dir)).sort()) {
    const p = join(root, dir, f);
    if (statSync(p).isFile() && f.endsWith('.py') && f !== '__init__.py') out[`${dir}/${f}`] = readFileSync(p, 'utf8');
  }
}
const body = `// GENERATED by scripts/gen-python-snippets.mjs from python/. Do not edit.\nexport const PY: Record<string, string> = ${JSON.stringify(out, null, 2)};\n`;
writeFileSync('src/content/python.generated.ts', body);
console.log(`python.generated.ts: ${Object.keys(out).length} files`);
